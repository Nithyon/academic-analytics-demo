import statistics

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from . import config  # noqa: E402

R = config.RESULTS_DIR
INK, INK2, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a"]  # validated categorical slots 1-3 (light)

plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 9, "axes.edgecolor": GRID,
                     "axes.labelcolor": INK2, "xtick.color": INK2, "ytick.color": INK2,
                     "axes.titlecolor": INK, "axes.facecolor": SURFACE, "figure.facecolor": SURFACE,
                     "axes.spines.top": False, "axes.spines.right": False})


def load_runs():
    runs = {}
    for p in sorted(R.glob("run_*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        runs[p.stem[4:]] = d
    return runs


def sm(run, key):
    return next((s for s in run["summary"] if s.get("key") == key), None)


def fmt(v, suf=""):
    return "â€“" if v is None else f"{v}{suf}"


def ci(s, k="ex_relaxed"):
    c = s.get(f"{k}_ci")
    return f"{s[k]} [{c[0]}, {c[1]}]" if c else fmt(s[k])


def paired_bootstrap(a_rows, b_rows, n=5000, seed=1):
    """95% CI for EX(a) - EX(b) on test items, resampling questions."""
    a = {r["id"]: r["relaxed"] for r in a_rows if r["split"] == "test"}
    b = {r["id"]: r["relaxed"] for r in b_rows if r["split"] == "test"}
    ids = sorted(set(a) & set(b))
    rng = random.Random(seed)
    diffs = []
    for _ in range(n):
        s = [rng.choice(ids) for _ in ids]
        diffs.append(100 * (sum(a[i] for i in s) - sum(b[i] for i in s)) / len(s))
    diffs.sort()
    point = 100 * (sum(a[i] for i in ids) - sum(b[i] for i in ids)) / len(ids)
    disc = (sum(a[i] and not b[i] for i in ids), sum(b[i] and not a[i] for i in ids))
    return round(point, 1), round(diffs[int(0.025 * n)], 1), round(diffs[int(0.975 * n)], 1), disc


def md_table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def tex_table(caption, label, head, rows, spec=None):
    spec = spec or "l" + "r" * (len(head) - 1)
    esc = lambda s: str(s).replace("%", r"\%").replace("&", r"\&").replace("_", r"\_").replace("â€“", "--")  # noqa: E731
    body = "\n".join(" & ".join(esc(c) for c in r) + r" \\" for r in rows)
    return (f"\\begin{{table*}}[t]\n\\centering\\small\n\\caption{{{caption}}}\\label{{{label}}}\n"
            f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{' & '.join(esc(h) for h in head)} \\\\\n\\midrule\n"
            f"{body}\n\\bottomrule\n\\end{{tabular}}\n\\end{{table*}}\n")


def main():
    runs = load_runs()
    md, tex = ["# Results tables (generated by backend/report.py)\n"], []
    llm_runs = {k: v for k, v in runs.items() if v["llm_mode"] == "ollama"}
    primary_key = next((k for k in llm_runs if "qwen2.5-coder" in k), next(iter(llm_runs), None))

    if primary_key:
        run = llm_runs[primary_key]
        model = run["model"]
        # ---- Table 1: main comparison
        head = ["Config", "EX relaxed [95% CI]", "EX strict", "Coverage", "Cond. acc.", "Wrong", "False-block",
                "Block rate", "Abstention", "R(Î»=2)", "R(Î»=10)", "p50 ms", "p95 ms", "Prompt tok."]
        rows = []
        for key in ("A", "B", "C"):
            s = sm(run, key)
            if s:
                rows.append([s["config"], ci(s), fmt(s["ex_strict"]), fmt(s["coverage"]), fmt(s["conditional_accuracy"]),
                             s["test_wrong"], fmt(s["false_block_rate"]), fmt(s["block_rate"]),
                             fmt(s["abstention_action_accuracy"]), s["reliability"]["2"], s["reliability"]["10"],
                             fmt(s["latency_p50_ms"]), fmt(s["latency_p95_ms"]), fmt(s["mean_prompt_tokens"])])
        n_test = sm(run, "C")["n_test"] if sm(run, "C") else "?"
        md += [f"## Table 1. Context configurations ({model}, {n_test} held-out test questions, 3 fixture databases)\n",
               md_table(head, rows), ""]
        tex.append(tex_table(f"Effect of prompt context ({model}). EX = execution accuracy on {n_test} held-out "
                             "questions, matched on three fixture databases; 95\\% Wilson intervals.", "tab:context",
                             head, rows))
        # ---- paired bootstrap
        boot = []
        for a, b in (("C", "B"), ("C", "A"), ("B", "A")):
            if a in run["items"] and b in run["items"]:
                p, lo, hi, disc = paired_bootstrap(run["items"][a], run["items"][b])
                boot.append([f"{a} âˆ’ {b}", p, f"[{lo}, {hi}]", f"{disc[0]} / {disc[1]}"])
        if boot:
            head_b = ["Difference", "Î” EX (pts)", "95% bootstrap CI", "Only-first / only-second correct"]
            md += ["## Table 2. Paired differences in execution accuracy\n", md_table(head_b, boot), ""]
            tex.append(tex_table("Paired bootstrap differences in relaxed EX (5,000 resamples of test questions).",
                                 "tab:boot", head_b, boot))
        # ---- Table 3: difficulty and category
        head_d = ["Config", "Easy", "Medium", "Hard", "Attendance", "Marks", "Combined", "Count"]
        rows_d = []
        for key in ("A", "B", "C"):
            s = sm(run, key)
            if not s:
                continue
            items = [r for r in run["items"][key] if r["split"] == "test"]
            cat = lambda c: fmt(round(100 * statistics.mean(r["relaxed"] for r in items if r["category"] == c), 1)  # noqa: E731
                                if any(r["category"] == c for r in items) else None)
            rows_d.append([s["config"], fmt(s["ex_by_difficulty"]["easy"]), fmt(s["ex_by_difficulty"]["medium"]),
                           fmt(s["ex_by_difficulty"]["hard"]), cat("attendance"), cat("marks"), cat("combined"),
                           cat("count")])
        md += ["## Table 3. Relaxed EX by difficulty and question category (%)\n", md_table(head_d, rows_d), ""]
        tex.append(tex_table("Relaxed EX (\\%) by difficulty and category.", "tab:difficulty", head_d, rows_d))
        # ---- Table 4: safety and governance ablation
        head_s = ["Config", "Block rate", "Unsafe reached DB (of 12)", "Personal-data leaks", "False-block",
                  "EX relaxed", "R(Î»=2)"]
        rows_s = []
        for key in ("C", "C-novalidator", "C-compromised", "C-compromised-novalidator", "C-noretry"):
            s = sm(run, key)
            if s:
                rows_s.append([s["config"], fmt(s["block_rate"]), s["unsafe_reached_db"], s["personal_data_leaks"],
                               fmt(s["false_block_rate"]), fmt(s["ex_relaxed"]), s["reliability"]["2"]])
        md += ["## Table 4. Governance ablations\n", md_table(head_s, rows_s), ""]
        tex.append(tex_table("Governance ablations: validator, compromised model and retry.", "tab:safety",
                             head_s, rows_s))
        # ---- Table 5: latency by stage
        head_l = ["Config", "Router", "Retrieval", "Generation", "Validation", "Execution", "Explanation", "p50 total", "p95 total"]
        rows_l = []
        for key in ("A", "B", "C"):
            s = sm(run, key)
            if s:
                st = s["stage_median_ms"]
                rows_l.append([s["config"]] + [fmt(st[k]) for k in ("router", "retrieval", "generation", "validation",
                                                                      "execution", "explanation")]
                              + [fmt(s["latency_p50_ms"]), fmt(s["latency_p95_ms"])])
        md += ["## Table 5. Median time per stage (ms)\n", md_table(head_l, rows_l), ""]
        tex.append(tex_table("Median time per pipeline stage (ms).", "tab:latency", head_l, rows_l))
        # ---- Table 6: other diagnostics
        head_o = ["Config", "Retry rate", "Hallucinated schema (1st attempt)", "Benign scary-word EX", "Context chars"]
        rows_o = [[sm(run, k)["config"], fmt(sm(run, k)["retry_rate"]), fmt(sm(run, k)["hallucinated_schema_first_attempt"]),
                   fmt(sm(run, k)["benign_ex"]), fmt(sm(run, k)["mean_context_chars"])]
                  for k in ("A", "B", "C") if sm(run, k)]
        md += ["## Table 6. Diagnostics\n", md_table(head_o, rows_o), ""]
        figures(run)

    # ---- model comparison (config C)
    rows_m = []
    for k, run in llm_runs.items():
        s = sm(run, "C")
        if s:
            rows_m.append([run["model"], ci(s), fmt(s["ex_strict"]), fmt(s["block_rate"]),
                           fmt(s["abstention_action_accuracy"]), s["reliability"]["2"], fmt(s["latency_p50_ms"])])
    if len(rows_m) > 1:
        head_m = ["Model (config C)", "EX relaxed [95% CI]", "EX strict", "Block rate", "Abstention", "R(Î»=2)", "p50 ms"]
        md += ["## Table 7. Model comparison\n", md_table(head_m, rows_m), ""]
        tex.append(tex_table("Local model comparison under configuration C.", "tab:models", head_m, rows_m))

    if "offline" in runs:
        s = sm(runs["offline"], "C")
        if s:
            md += ["## Offline stand-in (deterministic pattern model; safety demonstration only)\n",
                   md_table(["EX relaxed", "Block rate", "False-block", "Abstention"],
                            [[fmt(s["ex_relaxed"]), fmt(s["block_rate"]), fmt(s["false_block_rate"]),
                              fmt(s["abstention_action_accuracy"])]]), ""]
    (R / "tables.md").write_text("\n".join(md), encoding="utf-8")
    (R / "tables.tex").write_text("% generated by backend/report.py\n" + "\n".join(tex), encoding="utf-8")
    print("wrote", R / "tables.md", R / "tables.tex")


def _style(ax, title, ylabel=None):
    ax.set_title(title, loc="left", fontsize=10, fontweight="bold", pad=10)
    if ylabel:
        ax.set_ylabel(ylabel)
    ax.yaxis.grid(True, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)
    ax.tick_params(length=0)


def figures(run):
    keys = [k for k in ("A", "B", "C") if sm(run, k)]
    labels = {"A": "A Minimal", "B": "B Full schema", "C": "C RAG"}
    # Figure 1: EX by difficulty, three configurations
    fig, ax = plt.subplots(figsize=(6.2, 3.0))
    diffs = ["easy", "medium", "hard"]
    w = 0.26
    for i, k in enumerate(keys):
        vals = [sm(run, k)["ex_by_difficulty"][d] or 0 for d in diffs]
        xs = [j + (i - 1) * w for j in range(3)]
        bars = ax.bar(xs, vals, w - 0.03, color=SERIES[i], label=labels[k], edgecolor=SURFACE, linewidth=1)
        for b, v in zip(bars, vals):
            ax.text(b.get_x() + b.get_width() / 2, v + 1.5, f"{v:.0f}", ha="center", fontsize=7, color=INK2)
    ax.set_xticks(range(3), [d.capitalize() for d in diffs])
    ax.set_ylim(0, 105)
    _style(ax, "Execution accuracy by difficulty (held-out test set)", "Relaxed EX (%)")
    ax.legend(frameon=False, ncol=3, loc="upper right", fontsize=8)
    fig.tight_layout()
    fig.savefig(R / "fig_ex_difficulty.png", dpi=200)
    plt.close(fig)

    # Figure 2: reliability vs penalty
    fig, ax = plt.subplots(figsize=(4.6, 3.0))
    lams = config.PENALTIES
    for i, k in enumerate(keys):
        ys = [sm(run, k)["reliability"][str(l)] for l in lams]
        ax.plot(lams, ys, color=SERIES[i], linewidth=2, marker="o", markersize=5, label=labels[k])
        ax.text(lams[-1] + 0.3, ys[-1], labels[k], color=INK2, fontsize=7, va="center")
    ax.axhline(0, color=INK2, linewidth=0.6)
    ax.set_xticks(lams)
    ax.set_xlim(0.5, 13.5)
    ax.set_xlabel("Penalty for a wrong answer (Î»)")
    _style(ax, "Reliability score vs. penalty", "Mean score per item")
    ax.legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(R / "fig_reliability.png", dpi=200)
    plt.close(fig)

    # Figure 3: unsafe requests reaching the database
    skeys = [k for k in ("C", "C-novalidator", "C-compromised", "C-compromised-novalidator") if sm(run, k)]
    names = {"C": "Full system", "C-novalidator": "No validator", "C-compromised": "Compromised model",
             "C-compromised-novalidator": "Compromised,\nno validator"}
    fig, ax = plt.subplots(figsize=(5.2, 2.8))
    vals = [sm(run, k)["unsafe_reached_db"] for k in skeys]
    bars = ax.bar(range(len(skeys)), vals, 0.55, color=SERIES[0], edgecolor=SURFACE)
    for b, v in zip(bars, vals):
        ax.text(b.get_x() + b.get_width() / 2, v + 0.2, str(v), ha="center", fontsize=8, color=INK)
    ax.set_xticks(range(len(skeys)), [names[k] for k in skeys], fontsize=8)
    ax.set_ylim(0, 12.5)
    _style(ax, "Unsafe requests that reached the database (of 12)", "Requests")
    fig.tight_layout()
    fig.savefig(R / "fig_safety.png", dpi=200)
    plt.close(fig)

    # Figure 4: latency per stage, config C
    s = sm(run, "C")
    if s:
        st = s["stage_median_ms"]
        order = ["router", "retrieval", "generation", "validation", "execution", "explanation"]
        fig, ax = plt.subplots(figsize=(5.2, 2.6))
        vals = [st[k] or 0 for k in order]
        bars = ax.barh(range(len(order)), vals, 0.55, color=SERIES[0], edgecolor=SURFACE)
        for b, v in zip(bars, vals):
            ax.text(v + max(vals) * 0.01, b.get_y() + b.get_height() / 2, f"{v:,.1f} ms", va="center", fontsize=7,
                    color=INK2)
        ax.set_yticks(range(len(order)), [o.capitalize() for o in order])
        ax.invert_yaxis()
        ax.set_xlim(0, max(vals) * 1.22)
        ax.xaxis.grid(True, color=GRID, linewidth=0.6)
        ax.set_axisbelow(True)
        ax.tick_params(length=0)
        ax.set_title("Median time per stage, configuration C", loc="left", fontsize=10, fontweight="bold", pad=10)
        ax.set_xlabel("Milliseconds")
        fig.tight_layout()
        fig.savefig(R / "fig_latency.png", dpi=200)
        plt.close(fig)


if __name__ == "__main__":
    main()
